-- v7：提醒到点要真的响一声（作者报"提醒便签未弹出提醒"——此前只有那枚到期角标，
-- 全工程没有任何东西会响）。
--
-- 存的是**已经为哪一次发生弹过**，不是"上次弹表的时间"。为什么不存时间戳：
--   1. "只弹一次"这条口径要求每次发生各弹一次。存时间戳的话，用户改了到期时间
--      就得自己记得把那个时间戳也清掉，忘了就永远不响（"我明明设了提醒"最难查的那种）；
--   2. 存发生点，则改到期时间 = 发生点变了 = 自动重新生效，一行代码都不用手串。
-- 重复提醒（daily/weekly）按锚点 + 24h/7d 推发生点，弹过就把那一次的发生点记在这列上，
-- 下一次发生点不同，所以还会弹。
--
-- 这一列**不进前端的行模型**，`sticky::upsert` 的列清单里也没有它：那是扫描器自己的账本，
-- 让用户侧的一次普通保存把它冲掉，就会看到"提醒又哑了"。
ALTER TABLE stickies ADD COLUMN reminded_at INTEGER;
