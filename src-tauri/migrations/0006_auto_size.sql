-- v6：便签随内容自动长高（作者追加的模式）。三态，不是布尔——
--   NULL = 没表过态，跟全局那个开关（settings 的 `sticky.auto_size`）走；
--   1    = 这张强制自动；
--   0    = 这张强制固定。
-- 压成布尔就分不开"跟着全局走"和"我就是要固定"，而那正是这个模式要留的口子：
-- 全局开着的时候，还得能让某一张回到手拉的固定尺寸。
--
-- 不动 width/height 那两列：自动模式**不往那两列写**。用户手拉出来的"固定值"必须
-- 原样躺在行里，关掉自动那一刻就得回得去——写进去了就没有"回去"这回事了。
ALTER TABLE stickies ADD COLUMN auto_size INTEGER;
